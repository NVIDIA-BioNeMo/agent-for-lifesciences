"""Selection registry for tracking available selections via Redis.

This registry tracks selections created by structure_query tool calls,
making them available to subsequent tools like python_execute.

Selections are stored in Redis keyed by session_id so that they persist
across multiple chat requests within the same browser session and are
shared across all API pods.
"""

import json
import logging
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Optional

logger = logging.getLogger(__name__)

# Redis key TTL for selections (1 hour, refreshed on access)
SELECTION_TTL = 3600

# Maximum selections to keep per session
MAX_SELECTIONS = 10

# Who made a selection. A user's pick is deliberate work that cannot be
# regenerated by asking again, whereas an agent's probe is one query away, so
# when the registry is full it is the probes that are dropped first.
PROVENANCE_USER = "user"
PROVENANCE_AGENT = "agent"


@dataclass
class SelectionInfo:
    """Information about a registered selection."""

    reference: str  # e.g., "selection_abc123"
    molql: str  # The MolQL query that created this selection
    action: str  # The action performed (highlight, focus, select, info)
    atom_count: int
    residue_count: int
    summary: str  # Human-readable summary
    created_at: datetime = field(default_factory=datetime.utcnow)
    query_id: Optional[str] = None  # Original tool call ID for correlation
    provenance: str = PROVENANCE_AGENT  # "user" (picked in the viewer) or "agent"
    name: Optional[str] = None  # Short label the user or agent gave it
    parent: Optional[str] = None  # Selection this one was edited or derived from
    scope: str = "atom"  # "atom" (MolQL) or "residue" (picked residue by residue)
    # Compact, chain-grouped residue listing in author numbering, e.g.
    # "A: Y56 M115 S120-T125 (6 res)". Precomputed at registration because the
    # registry holds metadata only -- the atoms live in the artifact -- and the
    # prompt needs to say *what* was selected without loading them.
    residue_listing: str = ""
    # The design role this selection plays, and the role's parameter. A role
    # selection with no atoms is a tombstone: it removes the role.
    role: Optional[str] = None
    role_value: Any = None

    def to_brief(self) -> str:
        """Return a brief description for LLM context."""
        label = f"{self.name}: " if self.name else ""
        return f"{label}{self.reference} ({self.atom_count} atoms, {self.residue_count} residues)"

    def to_dict(self) -> dict:
        """Convert to dictionary for JSON serialization."""
        return {
            "reference": self.reference,
            "molql": self.molql,
            "action": self.action,
            "atom_count": self.atom_count,
            "residue_count": self.residue_count,
            "summary": self.summary,
            "created_at": self.created_at.isoformat(),
            "query_id": self.query_id,
            "provenance": self.provenance,
            "name": self.name,
            "parent": self.parent,
            "scope": self.scope,
            "residue_listing": self.residue_listing,
            "role": self.role,
            "role_value": self.role_value,
        }

    @classmethod
    def from_dict(cls, data: dict) -> "SelectionInfo":
        """Create from dictionary."""
        created_at = data.get("created_at")
        if isinstance(created_at, str):
            created_at = datetime.fromisoformat(created_at)
        elif created_at is None:
            created_at = datetime.utcnow()

        return cls(
            reference=data["reference"],
            molql=data.get("molql", ""),
            action=data.get("action", ""),
            atom_count=data.get("atom_count", 0),
            residue_count=data.get("residue_count", 0),
            summary=data.get("summary", ""),
            created_at=created_at,
            query_id=data.get("query_id"),
            provenance=data.get("provenance") or PROVENANCE_AGENT,
            name=data.get("name"),
            parent=data.get("parent"),
            scope=data.get("scope") or "atom",
            residue_listing=data.get("residue_listing") or "",
            role=data.get("role") or None,
            role_value=data.get("role_value"),
        )


def _redis_key(session_id: str) -> str:
    """Build Redis key for selection list."""
    return f"sel:{session_id}"


async def _get_selections_from_redis(redis_client, session_id: str) -> list[SelectionInfo]:
    """Read all selections for a session from Redis.
    
    Args:
        redis_client: Redis client instance.
        session_id: Browser session ID.
    
    Returns:
        List of SelectionInfo in insertion order (oldest first).
    """
    key = _redis_key(session_id)
    raw = await redis_client.get(key)
    if not raw:
        return []

    try:
        items = json.loads(raw)
        return [SelectionInfo.from_dict(item) for item in items]
    except Exception as e:
        logger.warning(f"Failed to deserialize selections for {session_id}: {e}")
        return []


async def _save_selections_to_redis(redis_client, session_id: str, selections: list[SelectionInfo]) -> None:
    """Write selections list to Redis.
    
    Args:
        redis_client: Redis client instance.
        session_id: Browser session ID.
        selections: List of SelectionInfo to store.
    """
    key = _redis_key(session_id)
    data = [sel.to_dict() for sel in selections]
    await redis_client.set(key, json.dumps(data), ex=SELECTION_TTL)


async def register_selection(
    redis_client,
    session_id: str,
    reference: str,
    molql: str,
    action: str,
    atom_count: int,
    residue_count: int,
    summary: str,
    query_id: Optional[str] = None,
    provenance: str = PROVENANCE_AGENT,
    name: Optional[str] = None,
    parent: Optional[str] = None,
    scope: str = "atom",
    residue_listing: str = "",
    role: Optional[str] = None,
    role_value: Any = None,
) -> SelectionInfo:
    """Register a new selection in Redis.

    Args:
        redis_client: Redis client instance.
        session_id: Browser session ID.
        reference: Storage reference ID (e.g., "selection_abc123")
        molql: The MolQL query that created this selection
        action: The action performed
        atom_count: Number of atoms in selection
        residue_count: Number of residues in selection
        summary: Human-readable summary
        query_id: Optional tool call ID for correlation. User selections have
            none: there is no tool call to correlate with.
        provenance: ``"user"`` or ``"agent"``.
        name: Optional short label.
        parent: Reference of the selection this one was derived from.
        scope: ``"atom"`` or ``"residue"``.
        residue_listing: Precomputed compact residue listing.
        role: Design role the selection plays, if any.
        role_value: The role's parameter (Float group, Burial level, layout).

    Returns:
        The registered SelectionInfo
    """
    selection = SelectionInfo(
        reference=reference,
        molql=molql,
        action=action,
        atom_count=atom_count,
        residue_count=residue_count,
        summary=summary,
        query_id=query_id,
        provenance=provenance,
        name=name,
        parent=parent,
        scope=scope,
        residue_listing=residue_listing,
        role=role,
        role_value=role_value,
    )

    selections = await _get_selections_from_redis(redis_client, session_id)
    selections.append(selection)

    # Trim to max size, oldest agent selection first. A user's pick is only
    # evicted once nothing else is left to drop, so an agent that probes the
    # structure ten times cannot push the user's hotspot out of the registry.
    while len(selections) > MAX_SELECTIONS:
        victim = next(
            (i for i, s in enumerate(selections[:-1]) if s.provenance != PROVENANCE_USER),
            0,
        )
        removed = selections.pop(victim)
        logger.debug(f"Removed selection from registry: {removed.reference}")

    await _save_selections_to_redis(redis_client, session_id, selections)

    logger.info(
        f"Registered selection: {reference} ({atom_count} atoms, "
        f"{residue_count} residues) for session {session_id}"
    )

    return selection


async def get_available_selections(redis_client, session_id: str = "default") -> list[SelectionInfo]:
    """Get all available selections (newest first).
    
    Args:
        redis_client: Redis client instance.
        session_id: Browser session ID.
    
    Returns:
        List of SelectionInfo, newest first.
    """
    selections = await _get_selections_from_redis(redis_client, session_id)
    return list(reversed(selections))


def active_role_layers(selections: list[SelectionInfo]) -> list[SelectionInfo]:
    """The selection currently playing each role, from oldest-first ``selections``.

    The newest selection for each ``(role, parameter)`` wins, and a role
    selection with no atoms removes the role. Returned in role order, so the
    layers read the same way each time.
    """
    from .design_spec import layer_key
    from .roles import ROLE_ORDER

    latest: dict[tuple[str, str], SelectionInfo] = {}
    for selection in selections:
        if not selection.role:
            continue
        key = layer_key(selection.role, selection.role_value)
        if selection.atom_count == 0:
            latest.pop(key, None)
        else:
            latest[key] = selection
    order = {role: i for i, role in enumerate(ROLE_ORDER)}
    return sorted(latest.values(), key=lambda s: order.get(s.role or "", len(order)))


async def get_role_layers(redis_client, session_id: str = "default") -> list[SelectionInfo]:
    """The selections currently playing a role in this session's design."""
    return active_role_layers(await _get_selections_from_redis(redis_client, session_id))


async def get_latest_selection(redis_client, session_id: str = "default") -> Optional[SelectionInfo]:
    """Get the most recently registered selection.
    
    Args:
        redis_client: Redis client instance.
        session_id: Browser session ID.
    """
    selections = await _get_selections_from_redis(redis_client, session_id)
    if not selections:
        return None
    return selections[-1]


async def get_latest_nonempty_selection(redis_client, session_id: str = "default") -> Optional[SelectionInfo]:
    """Get the most recent selection that has atoms.
    
    This is preferred for auto-injection into python_execute,
    as empty selections would cause computation errors.
    
    Args:
        redis_client: Redis client instance.
        session_id: Browser session ID.
    
    Returns:
        The most recent SelectionInfo with atom_count > 0, or None.
    """
    selections = await _get_selections_from_redis(redis_client, session_id)
    for selection in reversed(selections):
        if selection.atom_count > 0:
            return selection
    return None


async def get_selection_by_query_id(redis_client, session_id: str, query_id: str) -> Optional[SelectionInfo]:
    """Get a selection by its tool call query_id.
    
    Args:
        redis_client: Redis client instance.
        session_id: Browser session ID.
        query_id: The tool call ID that triggered the selection.
        
    Returns:
        The SelectionInfo if found, None otherwise.
    """
    selections = await _get_selections_from_redis(redis_client, session_id)
    for selection in selections:
        if selection.query_id == query_id:
            return selection
    return None


async def clear_selections(redis_client, session_id: str = "default") -> int:
    """Clear all selections for a session.
    
    Args:
        redis_client: Redis client instance.
        session_id: Browser session ID.
    
    Returns:
        Number of selections cleared.
    """
    key = _redis_key(session_id)
    selections = await _get_selections_from_redis(redis_client, session_id)
    count = len(selections)
    await redis_client.delete(key)
    logger.info(f"Cleared {count} selections for session {session_id}")
    return count


async def get_selection_state_condensed(redis_client, session_id: str = "default") -> str:
    """Get a condensed summary of available selections for context injection.
    
    Returns a compact representation like:
    - No selections: "[SELECTION STATE: No selections available]"
    - One selection: "[SELECTION STATE: selection_abc123 (214 atoms, 27 residues)]"
    - Multiple: "[SELECTION STATE: selection_abc123 (214 atoms); selection_xyz789 (37 atoms)]"
    
    Args:
        redis_client: Redis client instance.
        session_id: Browser session ID.
    
    Returns:
        Condensed string suitable for prompt injection.
    """
    selections = await get_available_selections(redis_client, session_id)
    
    if not selections:
        return "[SELECTION STATE: No selections available]"
    
    # Show up to 3 most recent selections
    parts = []
    for sel in selections[:3]:
        parts.append(f"{sel.reference} ({sel.atom_count} atoms, {sel.residue_count} residues)")
    
    result = f"[SELECTION STATE: {'; '.join(parts)}"
    
    if len(selections) > 3:
        result += f"; ... and {len(selections) - 3} more"
    
    result += "]"
    return result
